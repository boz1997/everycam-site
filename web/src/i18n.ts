const DICTS: Record<Lang, Dict> = { en, tr, es, de, fr, it, pt, nl, pl };
const STORE_KEY = 'sharecam.lang';

export function detectLang(): Lang {
  const saved = localStorage.getItem(STORE_KEY) as Lang | null;
  if (saved && LANGS.includes(saved)) return saved;
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase() as Lang;
  return LANGS.includes(nav) ? nav : 'en';
}

export function saveLang(lang: Lang): void {
  localStorage.setItem(STORE_KEY, lang);
}

/** Eksik anahtar İngilizceye düşer — hiçbir ekran boş metinle çıkmaz. */
export function makeT(lang: Lang) {
  const dict = DICTS[lang] ?? en;
  return (key: string): string => dict[key] ?? en[key] ?? key;
}
